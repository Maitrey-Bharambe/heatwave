// Generates the SQL files to paste into the Supabase SQL Editor:
//   supabase/schema.sql — tables, enums, keys, indexes (from the Prisma migration) + RLS lockdown
//   supabase/seed.sql   — states/UTs, monitoring locations, safety tips, emergency contacts
//   supabase/setup.sql  — schema.sql + seed.sql in one file (paste once, click Run)
// Run: node scripts/generate-supabase-sql.mjs
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { STATES } from '../lib/states.js';
import { SAFETY_TIPS, EMERGENCY_CONTACTS } from '../lib/referenceData.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const migrationsDir = path.join(root, 'prisma', 'migrations');
const migrations = fs.readdirSync(migrationsDir).filter((d) => fs.statSync(path.join(migrationsDir, d)).isDirectory()).sort();
const tables = [];

let schema = `-- ClimateIQ — Supabase schema
-- Paste into Supabase → SQL Editor → New query → Run (once, on an empty project).
-- Generated from prisma/migrations by scripts/generate-supabase-sql.mjs — do not edit by hand.

`;
const applied = [];
for (const m of migrations) {
  const raw = fs.readFileSync(path.join(migrationsDir, m, 'migration.sql'));
  applied.push({ name: m, checksum: crypto.createHash('sha256').update(raw).digest('hex') });
  const sql = raw.toString('utf8').replace(/\r\n/g, '\n');
  for (const match of sql.matchAll(/CREATE TABLE "([^"]+)"/g)) tables.push(match[1]);
  schema += `-- ───────── migration ${m} ─────────\n${sql.trim()}\n\n`;
}
schema += `-- ───────── Prisma migration history ─────────
-- Records the migrations above as applied, so \`prisma migrate deploy\` (run by Vercel's
-- build) sees no pending migrations instead of trying to create the tables again.
CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
    "id"                  VARCHAR(36) PRIMARY KEY NOT NULL,
    "checksum"            VARCHAR(64) NOT NULL,
    "finished_at"         TIMESTAMPTZ,
    "migration_name"      VARCHAR(255) NOT NULL,
    "logs"                TEXT,
    "rolled_back_at"      TIMESTAMPTZ,
    "started_at"          TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count" INTEGER NOT NULL DEFAULT 0
);
${applied.map((a) => `INSERT INTO "_prisma_migrations" ("id", "checksum", "finished_at", "migration_name", "applied_steps_count")
VALUES (gen_random_uuid()::text, '${a.checksum}', now(), '${a.name}', 1);`).join('\n')}

-- ───────── Row Level Security ─────────
-- ClimateIQ talks to Postgres only through Prisma on the server (as the table owner, which
-- bypasses RLS). Enabling RLS with NO policies blocks Supabase's public Data API (anon /
-- authenticated keys) from reading or writing these tables — e.g. users.passwordHash.
${[...tables, '_prisma_migrations'].map((t) => `ALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;`).join('\n')}
`;

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

let seed = `-- ClimateIQ — Supabase seed data (reference data only: no users, no weather values)
-- Run AFTER schema.sql. Safe to re-run.
-- Generated by scripts/generate-supabase-sql.mjs — do not edit by hand.

BEGIN;

-- 36 States and Union Territories (representative coordinates = first monitoring point)
INSERT INTO "states" ("name", "code", "type", "capital", "latitude", "longitude") VALUES
${STATES.map((s) => `  (${q(s.name)}, ${q(s.code)}, '${s.type}', ${q(s.capital)}, ${s.points[0][1]}, ${s.points[0][2]})`).join(',\n')}
ON CONFLICT ("code") DO UPDATE SET "name" = EXCLUDED."name", "type" = EXCLUDED."type", "capital" = EXCLUDED."capital",
  "latitude" = EXCLUDED."latitude", "longitude" = EXCLUDED."longitude";

-- Monitoring locations (real city coordinates; weather is fetched live, never stored here)
INSERT INTO "monitoring_locations" ("name", "stateId", "latitude", "longitude", "isRepresentative")
SELECT v.name, s.id, v.lat, v.lon, v.rep
FROM (VALUES
${STATES.flatMap((s) => s.points.map(([name, lat, lon], i) => `  (${q(name)}, ${q(s.code)}, ${lat}::float8, ${lon}::float8, ${i === 0})`)).join(',\n')}
) AS v(name, code, lat, lon, rep)
JOIN "states" s ON s.code = v.code
ON CONFLICT ("name", "stateId") DO UPDATE SET "latitude" = EXCLUDED."latitude", "longitude" = EXCLUDED."longitude",
  "isRepresentative" = EXCLUDED."isRepresentative";

-- Safety guidance (riskLevel NULL = applies to every level)
DELETE FROM "safety_tips";
INSERT INTO "safety_tips" ("riskLevel", "category", "title", "description", "sortOrder") VALUES
${SAFETY_TIPS.map(([level, category, title, description], i) => `  (${level ? `'${level}'` : 'NULL'}, ${q(category)}, ${q(title)}, ${q(description)}, ${i})`).join(',\n')};

-- Verified national emergency numbers
DELETE FROM "emergency_contacts";
INSERT INTO "emergency_contacts" ("name", "phone", "description", "source", "sortOrder") VALUES
${EMERGENCY_CONTACTS.map(([name, phone, description, source], i) => `  (${q(name)}, ${q(phone)}, ${q(description)}, ${q(source)}, ${i})`).join(',\n')};

COMMIT;

-- Check: expect 36, ${STATES.reduce((n, s) => n + s.points.length, 0)}, ${SAFETY_TIPS.length}, ${EMERGENCY_CONTACTS.length}
SELECT (SELECT count(*) FROM "states") AS states,
       (SELECT count(*) FROM "monitoring_locations") AS monitoring_locations,
       (SELECT count(*) FROM "safety_tips") AS safety_tips,
       (SELECT count(*) FROM "emergency_contacts") AS emergency_contacts;
`;

fs.mkdirSync(path.join(root, 'supabase'), { recursive: true });
fs.writeFileSync(path.join(root, 'supabase', 'schema.sql'), schema);
fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), seed);
fs.writeFileSync(path.join(root, 'supabase', 'setup.sql'), `${schema}
${seed}`);
console.log(`Wrote supabase/schema.sql (${tables.length} tables), supabase/seed.sql and supabase/setup.sql`);
